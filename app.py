"""
Electricity Consumption Forecasting — Dashboard

Run: streamlit run app.py
"""

import streamlit as st
import pandas as pd
import plotly.graph_objects as go
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent / "data"

st.set_page_config(page_title="Electricity Consumption Forecasting", layout="wide")

# ---------- Load data ----------
@st.cache_data
def load():
    processed = pd.read_csv(DATA_DIR / "processed.csv", index_col=0, parse_dates=True)
    preds = pd.read_csv(DATA_DIR / "predictions.csv", index_col=0, parse_dates=True)
    metrics = pd.read_csv(DATA_DIR / "metrics.csv")
    importance = pd.read_csv(DATA_DIR / "feature_importance.csv", index_col=0)
    forecast_path = DATA_DIR / "forecast.csv"
    forecast = pd.read_csv(forecast_path, index_col=0, parse_dates=True) if forecast_path.exists() else None
    return processed, preds, metrics, importance, forecast

processed, preds, metrics, importance, future_forecast = load()

# ---------- Header ----------
st.title("⚡ Electricity Consumption Forecasting")
st.caption(
    "Predicting hourly electricity load using historical usage patterns "
    "(UCI ElectricityLoadDiagrams dataset — hourly load, kW)."
)

# ---------- Top metrics ----------
best_model = metrics.sort_values("MAPE_%").iloc[0]
c1, c2, c3, c4 = st.columns(4)
c1.metric("Best model", best_model["model"])
c2.metric("MAE", f"{best_model['MAE']:.2f} kW")
c3.metric("RMSE", f"{best_model['RMSE']:.2f} kW")
c4.metric("MAPE", f"{best_model['MAPE_%']:.2f}%")

st.divider()

# ---------- Forward Forecast (genuine future prediction, beyond the dataset) ----------
if future_forecast is not None and len(future_forecast) > 0:
    st.subheader(f"Forecast — Next {len(future_forecast)} Hours")
    st.caption(
        "Generated by recursively feeding each hour's prediction back into the model "
        "as a lag feature for the next hour (run via src/forecast.py)."
    )
    fig_fc = go.Figure()
    fig_fc.add_trace(go.Scatter(
        x=future_forecast.index, y=future_forecast["predicted_load_kw"],
        name="Forecast", mode="lines+markers",
        line=dict(color="#f97316", width=2),
    ))
    fig_fc.update_layout(height=320, xaxis_title="Time", yaxis_title="Predicted load (kW)",
                          margin=dict(t=20))
    st.plotly_chart(fig_fc, use_container_width=True)
    st.divider()

# ---------- Actual vs Predicted ----------
st.subheader("Actual vs Predicted Load (last 14 days, held-out test set)")

model_choice = st.selectbox(
    "Model", ["xgboost", "linear_reg", "naive"],
    format_func=lambda x: {"xgboost": "XGBoost", "linear_reg": "Linear Regression",
                            "naive": "Naive (yesterday same hour)"}[x],
)

fig = go.Figure()
fig.add_trace(go.Scatter(x=preds.index, y=preds["actual"], name="Actual",
                          line=dict(color="#2563eb", width=2)))
fig.add_trace(go.Scatter(x=preds.index, y=preds[model_choice], name="Predicted",
                          line=dict(color="#f97316", width=2, dash="dot")))
fig.update_layout(height=420, xaxis_title="Time", yaxis_title="Load (kW)",
                   legend=dict(orientation="h", y=1.05), margin=dict(t=30))
st.plotly_chart(fig, use_container_width=True)

st.divider()

# ---------- Model comparison table ----------
col1, col2 = st.columns([1, 1])

with col1:
    st.subheader("Model comparison")
    st.dataframe(metrics.set_index("model"), use_container_width=True)
    st.caption("Lower is better for all three metrics. MAPE = mean absolute % error.")

with col2:
    st.subheader("What drives the prediction (XGBoost)")
    fig2 = go.Figure(go.Bar(
        x=importance["importance"].head(8)[::-1],
        y=importance.index[:8][::-1],
        orientation="h", marker_color="#2563eb",
    ))
    fig2.update_layout(height=320, margin=dict(t=10, l=10))
    st.plotly_chart(fig2, use_container_width=True)

st.divider()

# ---------- Historical patterns ----------
st.subheader("Historical usage patterns")
tab1, tab2, tab3 = st.tabs(["By hour of day", "By day of week", "Full history"])

with tab1:
    hourly = processed.groupby("hour")["load_kw"].mean()
    fig3 = go.Figure(go.Bar(x=hourly.index, y=hourly.values, marker_color="#22c55e"))
    fig3.update_layout(height=350, xaxis_title="Hour of day", yaxis_title="Avg load (kW)")
    st.plotly_chart(fig3, use_container_width=True)

with tab2:
    days = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    daily = processed.groupby("dayofweek")["load_kw"].mean()
    fig4 = go.Figure(go.Bar(x=days, y=daily.values, marker_color="#a855f7"))
    fig4.update_layout(height=350, xaxis_title="Day of week", yaxis_title="Avg load (kW)")
    st.plotly_chart(fig4, use_container_width=True)

with tab3:
    sample = processed["load_kw"].resample("1D").mean()
    fig5 = go.Figure(go.Scatter(x=sample.index, y=sample.values, line=dict(color="#0ea5e9")))
    fig5.update_layout(height=350, xaxis_title="Date", yaxis_title="Daily avg load (kW)")
    st.plotly_chart(fig5, use_container_width=True)

st.divider()
st.caption(
    "Data: UCI ElectricityLoadDiagrams20112014 (321 clients, resampled to hourly). "
    "Pipeline: src/pipeline.py -> src/train_model.py -> app.py"
)
